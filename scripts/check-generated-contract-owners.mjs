#!/usr/bin/env node
// Every file under the ts-rs export directory claims, in its own banner, to have
// been generated from a Rust source and to be unsafe to edit by hand. A file that
// carries that banner without an owning Rust type is a lie the repository tells
// itself: it cannot be renamed through its stated source, it cannot be verified
// against any Rust definition, and a hand edit to it is indistinguishable from a
// regeneration.
//
// This check proves the banner. Every exported type must resolve to a Rust type
// that derives `ts_rs::TS`, EXCEPT those enumerated in the quarantine register.
// The register is an EXACT set, not a floor: a new orphan fails, and an entry
// that has since acquired an owner also fails, forcing the list to shrink as
// owners are written. It is a named gap, not a silent allowance.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EXPORT_DIR = path.join(
  ROOT,
  "apps/hypervisor/src/generated/hypervisor-contracts",
);
const QUARANTINE = path.join(
  ROOT,
  "scripts/data/generated-contract-owner-quarantine.v1.json",
);
const CRATES = path.join(ROOT, "crates");
const TS_RS_BANNER = "generated by [ts-rs]";

function rustSources(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "target" || entry.name === "node_modules") continue;
      rustSources(full, out);
    } else if (entry.name.endsWith(".rs")) {
      out.push(full);
    }
  }
  return out;
}

// A Rust owner is a `struct`/`enum` whose derive list includes `TS`. The exported
// TypeScript name is the Rust identifier unless `#[ts(rename = "...")]` overrides
// it, so both spellings are collected.
function discoverRustOwners() {
  const owners = new Map();
  for (const file of rustSources(CRATES)) {
    const text = fs.readFileSync(file, "utf8");
    if (!text.includes("ts_rs::TS") && !text.includes("TS)]")) continue;
    const lines = text.split("\n");
    for (let index = 0; index < lines.length; index += 1) {
      const declaration = /^\s*pub(?:\([^)]*\))?\s+(?:struct|enum)\s+(\w+)/.exec(
        lines[index],
      );
      if (!declaration) continue;
      // Walk back over the attribute block immediately above the declaration.
      let derivesTs = false;
      let renamed = null;
      for (let back = index - 1; back >= 0; back -= 1) {
        const line = lines[back].trim();
        if (line.startsWith("///") || line.startsWith("//")) continue;
        if (!line.startsWith("#[")) break;
        if (/derive\([^)]*\bTS\b/.test(line)) derivesTs = true;
        const rename = /#\[ts\([^)]*rename\s*=\s*"([^"]+)"/.exec(line);
        if (rename) renamed = rename[1];
      }
      if (!derivesTs) continue;
      const exported = renamed ?? declaration[1];
      owners.set(exported, path.relative(ROOT, file));
    }
  }
  return owners;
}

function main() {
  const errors = [];
  const owners = discoverRustOwners();

  const generated = fs
    .readdirSync(EXPORT_DIR)
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .map((name) => name.replace(/\.ts$/, ""))
    .sort();

  const banners = new Map();
  for (const name of generated) {
    const text = fs.readFileSync(path.join(EXPORT_DIR, `${name}.ts`), "utf8");
    banners.set(name, text.includes(TS_RS_BANNER));
  }

  const unowned = generated.filter(
    (name) => banners.get(name) && !owners.has(name),
  );

  const register = JSON.parse(fs.readFileSync(QUARANTINE, "utf8"));
  const quarantined = [...register.orphaned_generated_contracts].sort();

  for (const name of unowned) {
    if (!quarantined.includes(name)) {
      errors.push(
        `${name}.ts claims ts-rs generation but no Rust type derives it, and it is not in the quarantine register. ` +
          `Write its owning Rust type, or register it explicitly in ${path.relative(ROOT, QUARANTINE)}.`,
      );
    }
  }
  for (const name of quarantined) {
    if (!generated.includes(name)) {
      errors.push(
        `${name} is quarantined but no longer exists under the export directory. Remove it from the register.`,
      );
    } else if (owners.has(name)) {
      errors.push(
        `${name} now has a Rust owner (${owners.get(name)}). Remove it from the register — the quarantine may only shrink.`,
      );
    }
  }

  // A file WITHOUT the banner in a directory that ts-rs owns is a hand-authored
  // contract hiding among generated ones; it would be silently overwritten.
  for (const name of generated) {
    if (!banners.get(name)) {
      errors.push(
        `${name}.ts sits in the ts-rs export directory without the generation banner. ` +
          `A regeneration would overwrite it without warning.`,
      );
    }
  }

  const owned = generated.filter((name) => owners.has(name));
  if (errors.length > 0) {
    console.error("check-generated-contract-owners: FAIL");
    for (const error of errors) console.error(`  - ${error}`);
    console.error(
      `\n  ${generated.length} generated contracts | ${owned.length} Rust-owned | ${quarantined.length} quarantined`,
    );
    process.exit(1);
  }
  console.log(
    `check-generated-contract-owners: OK — ${generated.length} generated contracts, ` +
      `${owned.length} Rust-owned, ${quarantined.length} quarantined without an owner.`,
  );
}

main();
