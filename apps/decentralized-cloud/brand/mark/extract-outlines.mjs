// EXTRACTS THE WORDMARK OUTLINES FROM THE DESIGNER'S SOURCE, once.
//
// The designer's file (source/FInal-CLOUD-v3.svg) sets the wordmark as outlined
// glyphs of IOI Display — measured against the face itself, glyph for glyph, the same
// drawing. The shipped face sets the name as LIVE TEXT in that font (owner ruling,
// 2026-09-05: one text run, no drawn letters), so the app never needs these paths.
// The downloadable SVG assets do, because a standalone .svg cannot carry the font.
//
// This script turns the source into wordmark-outlines.mjs. It is kept so the
// derivation is reproducible, not because it runs often: the source file is the
// designer's, and if it is replaced this is re-run and the diff is the whole story.
//
// Usage: node apps/decentralized-cloud/brand/mark/extract-outlines.mjs

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = readFileSync(path.join(HERE, "source/FInal-CLOUD-v3.svg"), "utf8")
  .replace(/<metadata>[\s\S]*?<\/metadata>/, "");

// The light lockup is the first; the dark one repeats the same paths in white.
const light = /<g id="lockup-light"[\s\S]*?<\/g>\s*<\/g>\s*<\/g>/.exec(src)?.[0];
if (!light) throw new Error("lockup-light group not found");

const group = (id) => {
  const m = new RegExp(`<g id="${id}">([\\s\\S]*?)</g>\\s*</g>`).exec(light);
  if (!m) throw new Error(`${id} group not found`);
  return [...m[1].matchAll(/<path d="([^"]+)"/g)].map((x) => x[1]);
};

const mark = group("mark");
const decentralized = group("decentralized");
// dot-cloud holds the five CLOUD glyphs in one fill and the dot in the gradient.
const dotCloudBlock = src.slice(src.indexOf('<g id="dot-cloud">'), src.indexOf('<g id="app-icon">'));
const fills = [...dotCloudBlock.matchAll(/<g fill="([^"]+)">([\s\S]*?)<\/g>/g)];
const cloud = [...fills[0][2].matchAll(/<path d="([^"]+)"/g)].map((x) => x[1]);
const dot = [...fills[1][2].matchAll(/<path d="([^"]+)"/g)].map((x) => x[1]);

const icon = /<g id="app-icon">([\s\S]*?)<\/g>\s*<\/g>/.exec(src)[1];
const iconPaths = [...icon.matchAll(/<path d="([^"]+)"/g)].map((x) => x[1]);

if (mark.length !== 3 || decentralized.length !== 13 || cloud.length !== 5 || dot.length !== 1 || iconPaths.length !== 3) {
  throw new Error(`unexpected counts: mark ${mark.length}, decentralized ${decentralized.length}, cloud ${cloud.length}, dot ${dot.length}, icon ${iconPaths.length}`);
}

const lit = (arr) => arr.map((d) => `  "${d}",`).join("\n");
const out = `// THE WORDMARK, OUTLINED — generated by extract-outlines.mjs from
// source/FInal-CLOUD-v3.svg. Do not edit by hand; re-run the extractor.
//
// These are IOI Display's own glyphs, outlined by the designer, in the lockup's
// coordinate space (the mark's 67.188-unit block; "decentralized" caps 0..22.072,
// "cloud" caps 29.188..67.188, x from 149.84). The shipped face does NOT use them:
// it sets the same name as live text in IOI.ttf. They exist so the downloadable
// SVG lockups render without the font.

export const DECENTRALIZED_PATHS = [
${lit(decentralized)}
];

export const CLOUD_PATHS = [
${lit(cloud)}
];
`;
writeFileSync(path.join(HERE, "wordmark-outlines.mjs"), out);
console.log("wrote wordmark-outlines.mjs");
console.log("MARK_PATHS =", JSON.stringify(mark, null, 1));
console.log("DOT_PATH =", JSON.stringify(dot[0]));
console.log("ICON_PATHS =", JSON.stringify(iconPaths, null, 1));
